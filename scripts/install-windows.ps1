# Windows / native PowerShell installer (for WSL users, run the Linux installer)
# Run from an elevated PowerShell: .\scripts\install-windows.ps1
$ErrorActionPreference = "Stop"

Write-Host "==> Installing Windows packages via winget" -ForegroundColor Cyan

$packages = @(
  "Git.Git",
  "Microsoft.PowerShell",
  "Neovim.Neovim",
  "junegunn.fzf",
  "BurntSushi.ripgrep",
  "sharkdp.fd",
  "sharkdp.bat",
  "eza-community.eza",
  "jesseduffield.lazygit",
  "dandavison.delta",
  "twpayne.chezmoi",
  "FiloSottile.age",
  "jqlang.jq",
  "Microsoft.VisualStudioCode",
  "GitHub.cli",
  "JanDeDobbeleer.OhMyPosh",
  "starship.starship",
  "ajeetdsouza.zoxide",
  "DEVCOM.JetBrainsMonoNerdFont",
  "DEVCOM.FiraCodeNerdFont"
)

foreach ($pkg in $packages) {
  Write-Host "  -> $pkg" -ForegroundColor Gray
  # Redirect stderr to null to keep output clean
  $output = winget install --id $pkg --silent --accept-package-agreements --accept-source-agreements 2>&1
  if ($LASTEXITCODE -ne 0) {
    Write-Host "    (warning: $pkg returned $LASTEXITCODE — may already be installed)" -ForegroundColor Yellow
  }
}

# Ghostty is not on winget; download from GitHub releases
Write-Host "==> Installing Ghostty" -ForegroundColor Cyan
$ghosttyUrl = "https://github.com/ghostty-org/ghostty/releases/latest/download/ghostty-windows-x86_64.zip"
$tmp = "$env:TEMP\ghostty.zip"
try {
  Invoke-WebRequest -Uri $ghosttyUrl -OutFile $tmp -UseBasicParsing
  Expand-Archive -Path $tmp -DestinationPath "$env:LOCALAPPDATA\Programs\Ghostty" -Force
} catch {
  Write-Host "  (warning: Ghostty download failed — install manually from https://ghostty.org)" -ForegroundColor Yellow
}

# Add Ghostty to PATH
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if ($userPath -notlike "*Ghostty*") {
  [Environment]::SetEnvironmentVariable("Path", "$userPath;$env:LOCALAPPDATA\Programs\Ghostty\bin", "User")
}

# PowerShell modules used by the profile (~/.config/powershell/profile.ps1)
Write-Host "==> Installing PowerShell modules" -ForegroundColor Cyan
foreach ($module in @("posh-git", "Terminal-Icons", "PSFzf")) {
  if (-not (Get-Module -ListAvailable -Name $module)) {
    Write-Host "  -> $module" -ForegroundColor Gray
    try {
      Install-Module -Name $module -Scope CurrentUser -Force -AllowClobber -Repository PSGallery -ErrorAction Stop
    } catch {
      Write-Host "    (warning: could not install $module — run: Install-Module $module -Scope CurrentUser)" -ForegroundColor Yellow
    }
  }
}

# Point every PowerShell host at the chezmoi-managed profile.
Write-Host "==> Linking PowerShell profile" -ForegroundColor Cyan
$profileTargets = @($PROFILE.CurrentUserAllHosts)
$pwsh = Get-Command pwsh -ErrorAction SilentlyContinue
if ($pwsh) {
  $pwshProfile = & $pwsh.Source -NoProfile -Command '$PROFILE.CurrentUserAllHosts'
  if ($pwshProfile) { $profileTargets += $pwshProfile }
} else {
  # PowerShell 7 was just installed but may not be on PATH in this session yet.
  $pwshDefault = Join-Path $HOME 'Documents/PowerShell/profile.ps1'
  if (Test-Path (Split-Path -Parent $pwshDefault)) {
    $profileTargets += $pwshDefault
  }
}

$shim = @'
# Generated by dotfiles/scripts/install-windows.ps1 — do not edit.
# The real profile is managed by chezmoi at ~/.config/powershell/profile.ps1.
. "$HOME/.config/powershell/profile.ps1"
'@

foreach ($target in ($profileTargets | Select-Object -Unique)) {
  $dir = Split-Path -Parent $target
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
  Set-Content -Path $target -Value $shim -Encoding utf8
  Write-Host "  -> $target" -ForegroundColor Gray
}

if (-not (Test-Path "$HOME/.config/powershell/profile.ps1")) {
  Write-Host "  (warning: run 'chezmoi apply' so ~/.config/powershell/profile.ps1 exists)" -ForegroundColor Yellow
}

# Gas town (Windows note): gas town is Linux/macOS-first.
# For WSL, install the Linux binaries inside your WSL distro instead.
Write-Host "==> Note: gas town runs in WSL/Linux. See https://github.com/gastownhall/gastown" -ForegroundColor Yellow

Write-Host "`n✓ Windows packages installed. Restart your shell." -ForegroundColor Green
